// scripts/generate-backend-manifest.mjs
// Hashes every regular file in the PyInstaller onedir sidecar and writes src/main/generated/backend-manifest.ts

import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'

const root = process.cwd()
const sidecarBuildDir = path.join(root, 'build', 'python-backend', 'jasper-backend')
const targetManifestTs = path.join(root, 'src', 'main', 'generated', 'backend-manifest.ts')

if (!fs.existsSync(sidecarBuildDir)) {
  console.error(`ERROR: Sidecar build directory not found at ${sidecarBuildDir}. Run "npm run build:python" first.`)
  process.exit(1)
}

function collectFiles(dir, base = dir) {
  let entries = []
  const items = fs.readdirSync(dir)
  for (const item of items) {
    const full = path.join(dir, item)
    const stat = fs.statSync(full)
    if (stat.isDirectory()) {
      entries = entries.concat(collectFiles(full, base))
    } else if (stat.isFile()) {
      const relPath = path.relative(base, full).replace(/\\/g, '/')
      const content = fs.readFileSync(full)
      const sha256 = crypto.createHash('sha256').update(content).digest('hex')
      entries.push({ path: relPath, sha256 })
    }
  }
  return entries
}

console.log(`==> Scanning and hashing files in ${sidecarBuildDir}...`)
const files = collectFiles(sidecarBuildDir)
files.sort((a, b) => a.path.localeCompare(b.path))

console.log(`==> Found ${files.length} sidecar files. Generating ${targetManifestTs}...`)

const lines = [
  '// Auto-generated by scripts/generate-backend-manifest.mjs - DO NOT EDIT MANUALLY',
  'export interface ManifestFileEntry {',
  '  path: string',
  '  sha256: string',
  '}',
  '',
  'export interface BackendManifest {',
  '  protocolVersion: 1',
  '  backendVersion: string',
  '  executable: string',
  '  files: ManifestFileEntry[]',
  '}',
  '',
  'export const DEFAULT_BACKEND_MANIFEST: BackendManifest = {',
  '  protocolVersion: 1,',
  "  backendVersion: '2.0.0',",
  "  executable: 'jasper-backend.exe',",
  '  files: ['
]

for (const f of files) {
  lines.push(`    { path: ${JSON.stringify(f.path)}, sha256: ${JSON.stringify(f.sha256)} },`)
}

lines.push('  ]', '}')
lines.push('')

fs.writeFileSync(targetManifestTs, lines.join('\n'), 'utf-8')
console.log(`==> Successfully generated backend manifest with ${files.length} entries.`)

